function pickEventImage(images) {
  if (!Array.isArray(images) || !images.length) return '';

  const wide = images.find((img) => img.ratio === '16_9' && img.width >= 640);
  return (wide || images[0])?.url || '';
}

// Normalizes a raw Ticketmaster Discovery API event into the same shape as INITIAL_EVENTS above,
// so EventCard / EventsView / EventDetailView work unchanged against real API data.
export function mapTicketmasterEvent(raw) {
  if (!raw) return null;

  const venue = raw._embedded?.venues?.[0];
  const classification = raw.classifications?.find((item) => item.primary) || raw.classifications?.[0];
  const priceRange = raw.priceRanges?.[0];
  const attraction = raw._embedded?.attractions?.[0];

  return {
    id: raw.id,
    title: raw.name,
    description: raw.info || raw.pleaseNote || '',
    importantNote: raw.pleaseNote || '',
    ticketUrl: raw.url || '',
    image: pickEventImage(raw.images),
    // Only present when the request included a latlong/geoPoint + radius — the distance from
    // that search origin to the event's venue, in whatever `units` ("miles"/"km") were requested.
    distance: typeof raw.distance === 'number' ? raw.distance : null,
    units: raw.units || '',
    date: {
      localDate: raw.dates?.start?.localDate || '',
      localTime: raw.dates?.start?.localTime || '',
      dateTime: raw.dates?.start?.dateTime || '',
      timezone: raw.dates?.timezone || '',
      status: raw.dates?.status?.code || '',
      dateTBD: Boolean(raw.dates?.start?.dateTBD),
      dateTBA: Boolean(raw.dates?.start?.dateTBA),
      timeTBA: Boolean(raw.dates?.start?.timeTBA),
      spanMultipleDays: Boolean(raw.dates?.spanMultipleDays),
    },
    venue: venue
      ? {
        id: venue.id,
        name: venue.name,
        address: venue.address?.line1 || '',
        city: venue.city?.name || '',
        state: venue.state?.name || '',
        stateCode: venue.state?.stateCode || '',
        country: venue.country?.name || '',
        countryCode: venue.country?.countryCode || '',
        postalCode: venue.postalCode || '',
        latitude: venue.location?.latitude || '',
        longitude: venue.location?.longitude || '',
        timezone: venue.timezone || '',
        url: venue.url || '',
        boxOfficeInfo: {
          phone: venue.boxOfficeInfo?.phoneNumberDetail || '',
          hours: venue.boxOfficeInfo?.openHoursDetail || '',
          acceptedPayment: venue.boxOfficeInfo?.acceptedPaymentDetail || '',
          willCall: venue.boxOfficeInfo?.willCallDetail || '',
        },
        parkingDetail: venue.parkingDetail || '',
        accessibleSeatingDetail: venue.accessibleSeatingDetail || '',
        generalRule: venue.generalInfo?.generalRule || '',
        childRule: venue.generalInfo?.childRule || '',
      }
      : null,
    price: priceRange
      ? { currency: priceRange.currency, min: priceRange.min, max: priceRange.max, type: priceRange.type }
      : null,
    sales: {
      publicStart: raw.sales?.public?.startDateTime || '',
      publicEnd: raw.sales?.public?.endDateTime || '',
      startTBD: Boolean(raw.sales?.public?.startTBD),
      presales: raw.sales?.presales || [],
    },
    seatmap: { imageUrl: raw.seatmap?.staticUrl || '' },
    accessibility: { info: raw.accessibility?.info || '' },
    ticketLimit: { info: raw.ticketLimit?.info || '' },
    ageRestrictions: { legalAgeEnforced: Boolean(raw.ageRestrictions?.legalAgeEnforced) },
    promoter: raw.promoter
      ? { id: raw.promoter.id, name: raw.promoter.name || '', description: raw.promoter.description || '' }
      : null,
    categories: {
      segment: classification?.segment?.name || '',
      genre: classification?.genre?.name || '',
      subGenre: classification?.subGenre?.name || '',
      type: classification?.type?.name || '',
      subType: classification?.subType?.name || '',
    },
    attractions: attraction
      ? [
        {
          id: attraction.id,
          name: attraction.name,
          url: attraction.url,
          image: attraction.images?.[0]?.url || '',
          socials: {
            instagram: attraction.externalLinks?.instagram?.[0]?.url || '',
            facebook: attraction.externalLinks?.facebook?.[0]?.url || '',
            twitter: attraction.externalLinks?.twitter?.[0]?.url || '',
            youtube: attraction.externalLinks?.youtube?.[0]?.url || '',
            homepage: attraction.externalLinks?.homepage?.[0]?.url || '',
          },
        },
      ]
      : [],
  };
}

export function formatEventDate(event) {
  const localDate = event?.date?.localDate || '';
  const localTime = event?.date?.localTime ? event.date.localTime.slice(0, 5) : '';

  return [localDate, localTime].filter(Boolean).join(' ');
}

export function formatEventDateTime(value) {
  if (!value) return '';

  return value.replace('T', ' ').replace(/:\d{2}Z$/, '');
}

export function formatEventVenue(event) {
  const venue = event?.venue;
  if (!venue) return '';

  const location = [venue.city, venue.stateCode].filter(Boolean).join(', ');

  return [venue.name, location].filter(Boolean).join(' - ');
}

export function formatEventClassifications(event) {
  const categories = event?.categories;
  if (!categories) return '';

  return [categories.segment, categories.genre, categories.subGenre].filter(Boolean).join(' / ');
}

export function formatEventPrice(event) {
  const price = event?.price;
  if (!price) return '';

  const currency = price.currency || 'USD';
  const formatter = new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency,
    maximumFractionDigits: 2,
  });

  if (price.min != null && price.max != null) {
    return `${formatter.format(price.min)} - ${formatter.format(price.max)}`;
  }

  if (price.min != null) return formatter.format(price.min);
  if (price.max != null) return formatter.format(price.max);

  return '';
}

export function mapEventToSuggestedItem(event) {
  if (!event) return null;

  const venueName = event?.venue?.name || '';
  const dateLabel = formatEventDate(event);
  const subtitleParts = [];

  if (venueName) subtitleParts.push(venueName);
  if (dateLabel) subtitleParts.push(dateLabel);

  return {
    id: event.id,
    title: event.title,
    subtitle: subtitleParts.join(' · '),
    image: event.image,
    price: formatEventPrice(event),
    categories: event?.categories?.genre || event?.categories?.segment || '',
  };
}

export function getSuggestedEvents(events = INITIAL_EVENTS, limit = 3) {
  return [...events]
    .sort((a, b) => {
      const dateA = a?.date?.localDate || '';
      const dateB = b?.date?.localDate || '';
      return dateA.localeCompare(dateB);
    })
    .slice(0, limit)
    .map(mapEventToSuggestedItem)
    .filter(Boolean);
}
